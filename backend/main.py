@app.post("/api/predict", response_model=PredictResponse)
def predict_insurance_cost(payload: PredictRequest):
    """
    Predicts medical insurance cost using Linear Regression:
    1. Runs input through Scikit-Learn Pipeline (Feature Engineering + Scaling + OLS Regressor).
    2. Computes predicted_usd.
    3. Translates to estimated_inr via:
       estimated_inr = predicted_usd * USD_TO_INR_RATE * INDIA_COST_FACTOR
    4. Computes risk categories and similar cohort statistics in both USD and INR.
    """
    if MODEL is None or DATA_DF is None:
        raise HTTPException(status_code=500, detail="Server assets not loaded.")

    # 1. Construct single-record DataFrame matching pipeline requirements
    input_data = pd.DataFrame([{
        "age": payload.age,
        "sex": payload.sex,
        "bmi": float(payload.bmi),
        "children": payload.children,
        "smoker": payload.smoker,
        "region": payload.region
    }])

    # 2. Execute pipeline inference
    try:
        raw_pred = float(MODEL.predict(input_data)[0])
        predicted_usd = round(max(0.0, raw_pred), 2)
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Model inference failed: {str(e)}")

    # 3. Apply configurable India INR conversion layer
    estimated_inr = to_inr(predicted_usd)

    # 4. Determine Risk Classification (based on USD thresholds)
    if predicted_usd < 10000:
        risk_level = "low"
        risk_label = "LOW RISK PROFILE"
        risk_badge_color = "emerald"
        risk_desc = "Standard preventative healthcare exposure. Low historical probability of high-cost claims."
    elif predicted_usd <= 25000:
        risk_level = "medium"
        risk_label = "MODERATE RISK PROFILE"
        risk_badge_color = "amber"
        risk_desc = "Moderate actuarial risk. Typical for older age brackets or overweight BMI ranges."
    else:
        risk_level = "high"
        risk_label = "HIGH RISK PROFILE"
        risk_badge_color = "rose"
        risk_desc = "Elevated actuarial risk profile primarily driven by tobacco use and/or clinical obesity."

    # 5. Cohort Benchmark Calculation (Same smoking status, Age +/- 5 years)
    cohort = DATA_DF[(DATA_DF["smoker"] == payload.smoker) & (DATA_DF["age"].between(payload.age - 5, payload.age + 5))]
    if len(cohort) > 0:
        cohort_avg_usd = round(float(cohort["charges"].mean()), 2)
    else:
        cohort_avg_usd = round(float(DATA_DF[DATA_DF["smoker"] == payload.smoker]["charges"].mean()), 2)

    overall_avg_usd = round(float(DATA_DF["charges"].mean()), 2)
    cohort_diff_usd = round(predicted_usd - cohort_avg_usd, 2)
    monthly_cost_usd = round(predicted_usd / 12, 2)

    cohort_avg_inr = to_inr(cohort_avg_usd)
    overall_avg_inr = to_inr(overall_avg_usd)
    cohort_diff_inr = round(estimated_inr - cohort_avg_inr, 2)
    monthly_cost_inr = round(estimated_inr / 12, 2)

    # 6. Formulate plain-English actuarial explanation
    reasons = []
    if payload.smoker == "yes":
        reasons.append("active smoking status adds a substantial risk premium loading in the linear regression model")
    else:
        reasons.append("non-smoker status preserves favorable baseline health rates")

    if payload.bmi >= 30.0:
        if payload.smoker == "yes":
            reasons.append(f"BMI of {payload.bmi:.1f} triggers the high-risk smoker x BMI interaction term")
        else:
            reasons.append(f"clinical obesity (BMI {payload.bmi:.1f} ≥ 30) adds cardiovascular/metabolic risk")
    elif payload.bmi >= 25.0:
        reasons.append(f"BMI of {payload.bmi:.1f} is in the overweight bracket with mild premium impact")
    else:
        reasons.append(f"BMI of {payload.bmi:.1f} falls in the optimal healthy weight range")

    reasons.append(f"age ({payload.age} years) adds standard linear chronological healthcare progression")

    explanation = f"Estimated using Linear Regression: {'; '.join(reasons)}. {risk_desc}"
    
    assumption_note = (
        f"Calculated as: estimated_inr = predicted_usd (${predicted_usd:,.2f}) * "
        f"USD_TO_INR_RATE ({USD_TO_INR_RATE}) * INDIA_COST_FACTOR ({INDIA_COST_FACTOR})."
    )

    disclaimer = "Model trained on US data. Amounts are India-adjusted estimates, not real insurance quotes."

    return PredictResponse(
        predicted_usd=predicted_usd,
        estimated_inr=estimated_inr,
        usd_to_inr_rate=USD_TO_INR_RATE,
        india_cost_factor=INDIA_COST_FACTOR,
        predicted_cost=estimated_inr,
        predicted_cost_usd=predicted_usd,
        risk_level=risk_level,
        risk_label=risk_label,
        risk_badge_color=risk_badge_color,
        average_cost_for_similar_profiles_usd=cohort_avg_usd,
        average_cost_for_similar_profiles_inr=cohort_avg_inr,
        average_cost_for_similar_profiles=cohort_avg_inr,
        cohort_difference_usd=cohort_diff_usd,
        cohort_difference_inr=cohort_diff_inr,
        overall_dataset_average_usd=overall_avg_usd,
        overall_dataset_average_inr=overall_avg_inr,
        monthly_equivalent_usd=monthly_cost_usd,
        monthly_equivalent_inr=monthly_cost_inr,
        assumption_note=assumption_note,
        explanation=explanation,
        disclaimer=disclaimer,
        input_received=payload
    )


@app.get("/api/eda")
def get_eda_data(
    region: Optional[List[str]] = Query(default=None),
    smoker: Optional[List[str]] = Query(default=None),
    age_min: Optional[int] = Query(default=None),
    age_max: Optional[int] = Query(default=None)
):
    """
    Computes sliced EDA dataset and distribution histograms for React interactive charts,
    supplying both USD and India-adjusted INR metrics.
    """
    if DATA_DF is None:
        raise HTTPException(status_code=500, detail="Dataset not loaded.")

    filtered_df = DATA_DF.copy()

    if isinstance(region, list) and len(region) > 0:
        filtered_df = filtered_df[filtered_df["region"].isin(region)]
    elif isinstance(region, str):
        filtered_df = filtered_df[filtered_df["region"] == region]

    if isinstance(smoker, list) and len(smoker) > 0:
        filtered_df = filtered_df[filtered_df["smoker"].isin(smoker)]
    elif isinstance(smoker, str):
        filtered_df = filtered_df[filtered_df["smoker"] == smoker]

    if isinstance(age_min, int):
        filtered_df = filtered_df[filtered_df["age"] >= age_min]
    if isinstance(age_max, int):
        filtered_df = filtered_df[filtered_df["age"] <= age_max]

    total_records = len(filtered_df)
    if total_records == 0:
        return {
            "total_records": 0,
            "conversion": {"usd_to_inr_rate": USD_TO_INR_RATE, "india_cost_factor": INDIA_COST_FACTOR},
            "charges_distribution": [],
            "averages_by_category": {},
            "scatter_age": [],
            "scatter_bmi": [],
            "correlation_matrix": []
        }

    # Charges Histogram (30 equal-width bins)
    charges_usd = filtered_df["charges"].values
    min_c_usd, max_c_usd = float(np.min(charges_usd)), float(np.max(charges_usd))
    bins = np.linspace(min_c_usd, max_c_usd, 31)

    hist_data = []
    for i in range(len(bins) - 1):
        low_usd, high_usd = bins[i], bins[i + 1]
        mask = (charges_usd >= low_usd) & (charges_usd <= high_usd) if i == len(bins) - 2 else (charges_usd >= low_usd) & (charges_usd < high_usd)
        subset = filtered_df[mask]
        smokers_c = int((subset["smoker"] == "yes").sum())
        nonsmokers_c = int((subset["smoker"] == "no").sum())
        
        low_inr = to_inr(low_usd)
        high_inr = to_inr(high_usd)
        center_usd = round((low_usd + high_usd) / 2, 2)
        center_inr = to_inr(center_usd)

        hist_data.append({
            "bin_label_usd": f"${int(low_usd):,}-${int(high_usd):,}",
            "bin_label_inr": f"₹{int(low_inr):,}-₹{int(high_inr):,}",
            "bin_center_usd": center_usd,
            "bin_center_inr": center_inr,
            "total": int(len(subset)),
            "smokers": smokers_c,
            "non_smokers": nonsmokers_c,
        })

    def format_cat_stats(col):
        grouped = filtered_df.groupby(col)["charges"].agg(["mean", "median", "count"]).reset_index()
        records = []
        for _, row in grouped.iterrows():
            avg_u = float(row["mean"])
            med_u = float(row["median"])
            records.append({
                "category": str(row[col]),
                "average_usd": round(avg_u, 2),
                "average_inr": to_inr(avg_u),
                "median_usd": round(med_u, 2),
                "median_inr": to_inr(med_u),
                "count": int(row["count"])
            })
        return records

    averages_by_category = {
        "smoker": format_cat_stats("smoker"),
        "sex": format_cat_stats("sex"),
        "region": format_cat_stats("region"),
        "children": format_cat_stats("children")
    }

    # Scatter Points: Age vs Charges and BMI vs Charges
    scatter_age = []
    for _, row in filtered_df[["age", "charges", "smoker", "bmi"]].iterrows():
        c_usd = round(float(row["charges"]), 2)
        scatter_age.append({
            "age": int(row["age"]),
            "cost_usd": c_usd,
            "cost_inr": to_inr(c_usd),
            "smoker": row["smoker"],
            "bmi": round(float(row["bmi"]), 2)
        })

    scatter_bmi = []
    for _, row in filtered_df[["bmi", "charges", "smoker", "age"]].iterrows():
        c_usd = round(float(row["charges"]), 2)
        scatter_bmi.append({
            "bmi": round(float(row["bmi"]), 2),
            "cost_usd": c_usd,
            "cost_inr": to_inr(c_usd),
            "smoker": row["smoker"],
            "age": int(row["age"])
        })

    # Correlation Matrix (unitless)
    corr_df = filtered_df[["age", "bmi", "children", "charges"]].copy()
    corr_df["smoker"] = (filtered_df["smoker"] == "yes").astype(int)
    corr_df["sex"] = (filtered_df["sex"] == "male").astype(int)
    corr_matrix = corr_df.corr().round(3)

    correlation_list = []
    for var1 in corr_matrix.columns:
        for var2 in corr_matrix.columns:
            correlation_list.append({
                "var1": var1,
                "var2": var2,
                "correlation": float(corr_matrix.loc[var1, var2])
            })

    mean_u = round(float(filtered_df["charges"].mean()), 2)
    med_u = round(float(filtered_df["charges"].median()), 2)

    return {
        "total_records": total_records,
        "dataset_size_overall": len(DATA_DF),
        "conversion": {
            "usd_to_inr_rate": USD_TO_INR_RATE,
            "india_cost_factor": INDIA_COST_FACTOR,
        },
        "mean_charges_usd": mean_u,
        "mean_charges_inr": to_inr(mean_u),
        "median_charges_usd": med_u,
        "median_charges_inr": to_inr(med_u),
        "min_charges_usd": round(min_c_usd, 2),
        "min_charges_inr": to_inr(min_c_usd),
        "max_charges_usd": round(max_c_usd, 2),
        "max_charges_inr": to_inr(max_c_usd),
        "charges_distribution": hist_data,
        "averages_by_category": averages_by_category,
        "scatter_age": scatter_age,
        "scatter_bmi": scatter_bmi,
        "correlation_matrix": correlation_list,
        "available_regions": list(DATA_DF["region"].unique()),
        "available_smokers": list(DATA_DF["smoker"].unique()),
        "age_bounds": {"min": int(DATA_DF["age"].min()), "max": int(DATA_DF["age"].max())}
    }


