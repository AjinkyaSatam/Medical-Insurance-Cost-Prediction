class PredictRequest(BaseModel):
    age: int = Field(..., ge=18, le=100, description="Age in years (18-100)")
    sex: Literal["female", "male"] = Field(..., description="Biological sex ('female' or 'male')")
    bmi: float = Field(..., ge=10.0, le=60.0, description="Body Mass Index (10.0-60.0 kg/m²)")
    children: int = Field(..., ge=0, le=10, description="Number of dependent children (0-10)")
    smoker: Literal["no", "yes"] = Field(..., description="Tobacco smoking status ('no' or 'yes')")
    region: Literal["northeast", "northwest", "southeast", "southwest"] = Field(
        ..., description="US dataset region (Indian cities are not in the US training data)"
    )


class PredictResponse(BaseModel):
    # Core predictions
    predicted_usd: float
    estimated_inr: float
    usd_to_inr_rate: float
    india_cost_factor: float
    
    # Backwards-compatible aliases
    predicted_cost: float  # Defaults to estimated_inr
    predicted_cost_usd: float

    # Risk assessment
    risk_level: Literal["low", "medium", "high"]
    risk_label: str
    risk_badge_color: str

    # Cohort Benchmarks (both USD and INR)
    average_cost_for_similar_profiles_usd: float
    average_cost_for_similar_profiles_inr: float
    average_cost_for_similar_profiles: float  # INR default for backward compatibility
    cohort_difference_usd: float
    cohort_difference_inr: float
    overall_dataset_average_usd: float
    overall_dataset_average_inr: float
    monthly_equivalent_usd: float
    monthly_equivalent_inr: float

    # Notes & Explanations
    assumption_note: str
    explanation: str
    disclaimer: str
    input_received: PredictRequest


